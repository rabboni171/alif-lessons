package main

import "fmt"

// Урок 10, Шаг 5: структура - значимый тип, при присваивании копируется целиком

type User struct {
	Name string
	Age  int
}

func main() {
	a := User{Name: "Али", Age: 25}
	b := a // 

	b.Name = "Изменённый"

	fmt.Println(a.Name) // Али - оригинал не тронут
	fmt.Println(b.Name) // Изменённый
}

