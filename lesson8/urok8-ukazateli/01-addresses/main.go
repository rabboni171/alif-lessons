package main

import "fmt"

// Урок 8, Шаг 1: смотрим, что скрывается за переменной - у неё есть адрес в памяти

func main() {
	x := 42
	fmt.Println("Значение x:", x) // 42 
	fmt.Println("Адрес x:   ", &x)     // например 0xc000014098
	fmt.Printf("Тип &x:     %T\n", &x) // *int
}

// запусти дважды - адрес будет разным.
// объясни: ОС выделяет память заново при каждом запуске программы
