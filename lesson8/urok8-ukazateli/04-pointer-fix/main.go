package main

import "fmt"

// Урок 8, Шаг 4: решение - передать не значение, а адрес переменной

func addOne(n *int) {
	*n = *n + 1
}

func main() {
	x := 5
	addOne(&x)
	fmt.Println("Снаружи x =", x) // 6
}

// разбери три изменения по сравнению с прошлым шагом:
// 1) тип параметра теперь *int
// 2) внутри функции работаем через *n
// 3) при вызове передаём &x, а не x
