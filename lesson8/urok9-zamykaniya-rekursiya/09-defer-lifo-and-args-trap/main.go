package main

import "fmt"

// Урок 9, Шаг 8 (часть 2/3): несколько defer выполняются в обратном порядке
// (стек: LIFO), а их аргументы вычисляются сразу, а не в момент вызова

func main() {
	for i := 1; i <= 3; i++ {
		defer fmt.Println("defer", i)
	}
	fmt.Println("основной код")
	// вывод:
	// основной код
	// defer 3
	// defer 2
	// defer 1

	x := 10
	defer fmt.Println("значение x при defer:", x) // 10, зафиксировано сразу
	x = 999
	fmt.Println("текущее x:", x) // 999
}

