package main

import "fmt"

// все аргументы в Go передаются копией.
// изменение параметра внутри функции не влияет на оригинал снаружи

func tryChange(n int) {
	n = 999
	fmt.Println("Внутри функции:", n)
}

// исключение по ощущениям - срезы: копируется сам "заголовок" среза,
// но данные внутри него общие, поэтому изменение элемента видно снаружи
// (вспомни урок про срезы)
func changeSlice(s []int) {
	s[0] = 999
}

func main() {
	x := 5
	tryChange(x)
	fmt.Println("Снаружи:", x) // всё ещё 5!

	nums := []int{1, 2, 3}
	changeSlice(nums)
	fmt.Println(nums) // [999 2 3] - изменился!

	// почему число не поменялось, а элемент среза поменялся?
	// разберём подробно на следующем уроке про указатели
}
