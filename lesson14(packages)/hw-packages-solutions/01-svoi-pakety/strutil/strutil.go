package strutil

// Reverse разворачивает строку по рунам (а не по байтам - иначе
// сломались бы многобайтовые символы, например кириллица).
func Reverse(s string) string {
	runes := []rune(s)
	for i, j := 0, len(runes)-1; i < j; i, j = i+1, j-1 {
		runes[i], runes[j] = runes[j], runes[i]
	}
	return string(runes)
}

// IsPalindrome использует Reverse внутри своего же пакета - вызывать
// её снаружи не обязательно, экспортируем только то, что нужно вызывающему.
//
// Это простая версия: сравнение точное, регистр и пробелы важны.
// Поэтому "топот" - палиндром, а "А роза упала" - нет (не совпадут
// заглавная "А" в начале и строчная "а" в конце, плюс пробелы).
func IsPalindrome(s string) bool {
	return s == Reverse(s)
}
