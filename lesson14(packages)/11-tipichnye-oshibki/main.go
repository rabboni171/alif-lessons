package main

import "fmt"

// Этот файл не про один баг, а про подборку типичных ошибок с пакетами.
// Большинство из них - ошибки компиляции, поэтому рабочий код и
// "поломки" тут соседствуют как закомментированные примеры с разбором.

func main() {
	fmt.Println("Разбор типичных ошибок с пакетами (см. комментарии ниже)")

	// Поломка 1 - маленькая буква у функции/типа/поля.
	// mathutil.validate(5)
	// undefined: mathutil.validate
	// Решение: если нужно вызывать снаружи пакета - имя с большой буквы.

	// Поломка 2 - путь импорта без имени модуля.
	// import "mathutil"
	// package mathutil is not in std
	// Решение: писать полный путь от модуля, например "myapp/mathutil"
	// (смотри в go.mod, как называется твой модуль).

	// Поломка 3 - разные package в одной папке.
	// Один файл начинается с "package mathutil", другой - с "package other",
	// оба лежат в папке mathutil/.
	// found packages mathutil and other in /path/mathutil
	// Решение: у всех .go файлов одной папки - одно и то же имя пакета.

	// Поломка 4 - циклический импорт.
	// Пакет models импортирует storage, а storage импортирует models.
	// import cycle not allowed
	// Решение: вынести общее в третий пакет либо использовать интерфейс.

	// Поломка 5 - неиспользуемый импорт.
	// import (
	//     "fmt"
	//     "strings" // не используется нигде в файле
	// )
	// "strings" imported and not used
	// Решение: убрать импорт или начать его использовать. goimports
	// умеет чистить такое автоматически.

	// Поломка 6 - забыли go mod init.
	// go run main.go
	// go: cannot find main module
	// Решение: go mod init имя_модуля один раз в корне проекта.

	// Поломка 7 - go run main.go при нескольких файлах в пакете main.
	// Если main.go пользуется функцией из helper.go в той же папке,
	// "go run main.go" не увидит helper.go и выдаст:
	// undefined: someHelperFunction
	// Решение: "go run ." - запускает весь пакет текущей папки,
	// а не один конкретный файл.

	// Поломка 8 - не сделали go mod tidy после go get.
	// go.mod пухнет от зависимостей, которые больше не импортируются
	// нигде в коде (или, наоборот, чего-то не хватает в require).
	// Решение: периодически запускать "go mod tidy" - подчистит лишнее,
	// добавит недостающее и обновит go.sum.
}
